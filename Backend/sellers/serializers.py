class SellerOrderSerializer(serializers.Serializer):
    """What a seller may know about an order: where to ship it and their own lines.

    Deliberately absent: order.total (includes other sellers' items), the buyer's
    account/email, other sellers' items, payment identifiers.
    """

    id = serializers.IntegerField(read_only=True)
    created_at = serializers.DateTimeField(read_only=True)
    paid_at = serializers.DateTimeField(read_only=True)
    shipping_name = serializers.CharField(read_only=True)
    shipping_phone = serializers.CharField(read_only=True)
    shipping_address = serializers.CharField(read_only=True)
    items = SellerOrderItemSerializer(source="seller_items", many=True, read_only=True)
    subtotal = serializers.SerializerMethodField()
    fulfillment_status = serializers.SerializerMethodField()

    def get_subtotal(self, order):
        return str(sum((i.line_total for i in order.seller_items), Decimal("0.00")))

    def get_fulfillment_status(self, order):
        statuses = [i.fulfillment_status for i in order.seller_items]
        return min(statuses, key=STAGE.__getitem__) if statuses else None


class FulfillmentUpdateSerializer(serializers.Serializer):
    status = serializers.ChoiceField(choices=["shipped", "delivered"])
    courier = serializers.CharField(max_length=50, required=False, allow_blank=True)
    tracking_number = serializers.CharField(max_length=100, required=False, allow_blank=True)

    def validate(self, attrs):
        if attrs["status"] == "shipped" and not attrs.get("courier", "").strip():
            raise serializers.ValidationError({"courier": "Courier is required when shipping."})
        return attrs
