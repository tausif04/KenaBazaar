# ---------- products ----------

class SellerProductSerializer(ProductSerializer):
    # at least one category, or the product can never be found by category filter
    categories = serializers.PrimaryKeyRelatedField(
        many=True, queryset=Category.objects.all(), allow_empty=False,
    )

    class Meta(ProductSerializer.Meta):
        # slug is generated by Product.save(); a client-chosen slug could squat
        # another product's URL.
        read_only_fields = ("slug", "created_at", "updated_at")

    def validate(self, attrs):
        regular = attrs.get("regular_price", getattr(self.instance, "regular_price", None))
        sale = attrs.get("sale_price", getattr(self.instance, "sale_price", None))
        if regular is not None and regular <= 0:
            raise serializers.ValidationError({"regular_price": "Must be greater than zero."})
        if sale is not None and regular is not None and sale >= regular:
            raise serializers.ValidationError(
                {"sale_price": "Sale price must be lower than the regular price."}
            )
        return attrs

    def create(self, validated_data):
        categories = validated_data.pop("categories")
        product = super(ProductSerializer, self).create(validated_data)  # ModelSerializer.create
        product.categories.set(categories)
        return product

    def update(self, instance, validated_data):
        categories = validated_data.pop("categories", None)
        instance = super(ProductSerializer, self).update(instance, validated_data)
        if categories is not None:
            instance.categories.set(categories)
        return instance


class SellerVariantSerializer(serializers.ModelSerializer):
    class Meta:
        model = ProductVariant
        fields = ("id", "size", "color", "sku", "stock")
        extra_kwargs = {"stock": {"max_value": MAX_STOCK}}   # DB integer overflow would be a 500

    def validate(self, attrs):
        for key in ("size", "color"):
            if key in attrs:
                attrs[key] = (attrs[key] or "").strip() or None   # "" and null mean the same
        size = attrs.get("size", getattr(self.instance, "size", None))
        color = attrs.get("color", getattr(self.instance, "color", None))
        clash = ProductVariant.objects.filter(
            product=self.context["product"], size=size, color=color,
        )
        if self.instance:
            clash = clash.exclude(pk=self.instance.pk)
        # product is not a serializer field, so DRF's automatic unique_together
        # validator cannot see it; without this check the DB raises a 500.
        if clash.exists():
            raise serializers.ValidationError(
                "This product already has a variant with that size and color."
            )
        return attrs


class SellerImageSerializer(serializers.ModelSerializer):
    class Meta:
        model = ProductImage
        fields = ("id", "image", "alt_text", "is_primary")

    def validate_image(self, value):
        if value.size > MAX_IMAGE_BYTES:
            raise serializers.ValidationError("Image must be 5 MB or smaller.")
        # Pillow has already proven this is a real image; restrict the formats we host.
        if getattr(value, "content_type", None) not in ALLOWED_IMAGE_TYPES:
            raise serializers.ValidationError("Use a JPEG, PNG or WebP image.")
        return value


