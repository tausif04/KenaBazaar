# ---------- profile / application ----------

class SellerApplySerializer(serializers.ModelSerializer):
    class Meta:
        model = SellerProfile
        fields = ("shop_name", "slug", "phone", "status")
        # status/slug are shown in the response but can never be set by the client
        # (otherwise anyone could POST {"status": "approved"} and skip review).
        read_only_fields = ("slug", "status")

    def validate(self, attrs):
        if hasattr(self.context["request"].user, "seller_profile"):
            raise serializers.ValidationError("You already have a seller application.")
        return attrs


